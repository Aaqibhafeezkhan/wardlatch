/** A lockfile of `kind` pinning a few packages, one of them the incident's package at a version in an affected range. */
function lockText(g, kind) {
  const pkgs = g.shuffle(OTHERS).slice(0, g.int(5)).map((n) => [n, ver(g)]);
  pkgs.push([VULN, `19.${g.pick(['0', '1', '2'])}.${g.int(9)}`]);
  pkgs.sort((a, b) => a[0].localeCompare(b[0]));
  if (kind === 'npm') return JSON.stringify({ name: 'app', version: '1.0.0', lockfileVersion: 3, requires: true, packages: { '': { name: 'app', dependencies: Object.fromEntries(pkgs.map(([n, v]) => [n, `^${v}`])) }, ...Object.fromEntries(pkgs.map(([n, v]) => [`node_modules/${n}`, { version: v, resolved: `https://registry.npmjs.org/${n}/-/${n.split('/').pop()}-${v}.tgz`, integrity: `sha512-${b64(g)}` }])) } }, null, 2);
  if (kind === 'yarn') return `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n${pkgs.map(([n, v]) => `"${n}@^${v}":\n  version "${v}"\n  resolved "https://registry.yarnpkg.com/${n}/-/${n.split('/').pop()}-${v}.tgz#${b64(g, 20).replace(/[+/=]/g, 'a')}"\n  integrity sha512-${b64(g)}\n`).join('\n')}`;
  const key = (n, v) => (n.startsWith('@') ? `'${n}@${v}'` : `${n}@${v}`);
  return `lockfileVersion: '9.0'\n\nsettings:\n  autoInstallPeers: true\n  excludeLinksFromLockfile: false\n\nimporters:\n\n  .:\n    dependencies:\n${pkgs.map(([n, v]) => `      ${n.startsWith('@') ? `'${n}'` : n}:\n        specifier: ^${v}\n        version: ${v}\n`).join('')}\npackages:\n\n${pkgs.map(([n, v]) => `  ${key(n, v)}:\n    resolution: {integrity: sha512-${b64(g)}}\n    engines: {node: '>=18'}\n`).join('\n')}\nsnapshots:\n\n${pkgs.map(([n, v]) => `  ${key(n, v)}: {}\n`).join('\n')}`;
}
const FILE = { npm: 'package-lock.json', yarn: 'yarn.lock', pnpm: 'pnpm-lock.yaml' };
/** What a lockfile at `path` comes to: 'SAFE' (read to its end, nothing listed in it is affected), or the worst row. */
const verdictOf = (L, path, kind) => {
  const r = L.lockfiles.checkLockfile({ path, kind }, RULE);
  const s = r.rows.map((x) => x.status);
  return s.includes('EXPOSED') ? 'EXPOSED' : s.includes('UNKNOWN') || !r.read ? 'UNKNOWN' : s.includes('REVIEW') ? 'REVIEW' : 'SAFE';
};
/** Every lockfile under `roots` as the CLI judges them: [{ path, verdict }] and the gap lists. */
const walkVerdicts = (L, roots) => {
  const denied = [], links = [], deep = [];
  const found = L.lockfiles.lockfilesUnder(roots, L.lockfiles.LOCK_DEPTH, denied, links, { deep });
  return { rows: found.map((f) => ({ path: f.path, verdict: verdictOf(L, f.path, f.kind) })), denied, links, deep };
};


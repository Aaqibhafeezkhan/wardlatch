/** Where in `text` a cut leaves a quoted string (or, for pnpm, a { } mapping) open: the cuts a package manager's own
 *  parser refuses. A cut at a line's end may be a shorter, valid file, and is not one of these. */
function openCuts(text, kind) {
  const at = []; let q = null, depth = 0;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) { if (ch === '\\' && q === '"') { i++; continue; } if (ch === q) q = null; else at.push(i + 1); continue; }
    if (ch === '"' || (kind === 'pnpm' && ch === '\'')) { q = ch; continue; }
    if (kind === 'pnpm' && ch === '{') depth++;
    else if (kind === 'pnpm' && ch === '}') depth--;
    else if (depth > 0 && ch !== '\n') at.push(i + 1);
  }
  return kind === 'npm' ? Array.from({ length: text.length - 1 }, (_, i) => i + 1) : [...new Set(at)].filter((i) => i < text.length);
}
/** b1: a lockfile cut inside a string or mapping (a write that stopped, a disk that filled) never reads SAFE when the whole
 *  file is EXPOSED. */
const b1 = (L) => property('b1 a cut lockfile', (g) => {
  const kind = g.pick(['npm', 'yarn', 'pnpm']), text = lockText(g, kind);
  const d = T.fresh('b1'), p = join(d, FILE[kind]);
  writeFileSync(p, text);
  if (verdictOf(L, p, kind) !== 'EXPOSED') return { kind, whole: verdictOf(L, p, kind), text };
  const cuts = openCuts(text, kind);
  for (let k = 0; k < Math.min(12, cuts.length); k++) {
    const at = g.pick(cuts);
    writeFileSync(p, text.slice(0, at));
    const v = verdictOf(L, p, kind);
    if (v === 'SAFE') return { kind, cutAt: at, of: text.length, endsWith: text.slice(Math.max(0, at - 40), at), verdict: v };
  }
  return null;
});
/** b2: nothing to read never reads SAFE: a lockfile that is empty, gone, a folder, a link to nothing or to itself, a FIFO,
 *  unreadable, or not text. */
const b2 = (L) => {
  const out = [];
  for (const kind of ['npm', 'yarn', 'pnpm']) {
    const shapes = {
      empty: (p) => writeFileSync(p, ''),
      'one newline': (p) => writeFileSync(p, '\n'),
      'NUL bytes': (p) => writeFileSync(p, Buffer.alloc(64)),
      'a BOM alone': (p) => writeFileSync(p, '﻿'),
      'random bytes': (p) => writeFileSync(p, Buffer.from(Array.from({ length: 200 }, (_, i) => (i * 7919 + 13) % 256))),
      'a folder': (p) => mkdirSync(p),
      'a link to nothing': (p) => symlinkSync(join(dirname(p), 'gone'), p),
      'a link to itself': (p) => symlinkSync(p, p),
      ...(process.platform !== 'win32' ? { 'a FIFO': (p) => execFileSync('mkfifo', [p]) } : {}),
      ...(AS_ROOT ? {} : { unreadable: (p) => { writeFileSync(p, lockText({ next: () => 0.5, int: () => 1, pick: (a) => a[0], shuffle: (a) => a, chance: () => false }, kind)); chmodSync(p, 0o000); } }),
    };
    for (const [what, make] of Object.entries(shapes)) {
      const d = T.fresh('b2'), p = join(d, FILE[kind]);
      make(p);
      const v = verdictOf(L, p, kind);
      if (v === 'SAFE') out.push(`${kind} ${what}: SAFE`);
      try { chmodSync(p, 0o644); } catch { /* a link or gone */ }
    }
  }
  return out.length ? `b2 nothing read as SAFE: ${out.join('; ')}` : null;
};


const OTHERS = ['left-pad', 'react', 'react-dom', 'scheduler', 'loose-envify', 'js-tokens', '@babel/core', '@scope/thing', 'react-server-dom-webpack-extra', 'next'];
const ver = (g) => `${g.int(30)}.${g.int(20)}.${g.int(40)}`;

/** A tree of projects: some lockfiles exposed, some clean, some unreadable, a link to a project inside the tree. */
function tree(g, tag) {
  const root = T.fresh(tag);
  const n = 3 + g.int(5);
  for (let i = 0; i < n; i++) {
    const depth = 1 + g.int(4), parts = Array.from({ length: depth }, () => `p${g.int(4)}`);
    // one lockfile in the folder, or two of different kinds (npm and yarn side by side, as a migration leaves them)
    for (const kind of g.chance(0.35) ? g.shuffle(['npm', 'yarn', 'pnpm']).slice(0, 2) : [g.pick(['npm', 'yarn', 'pnpm'])]) {
      const text = g.chance(0.25) ? '' : lockText(g, kind);
      try { T.put(join(root, ...parts, `${i}`, FILE[kind]), g.chance(0.2) ? text.replace(/19\.(\d)\.(\d)/g, '20.$1.$2') : text); } catch { /* a name the walk below already made a file */ }
    }
  }
  return root;
}

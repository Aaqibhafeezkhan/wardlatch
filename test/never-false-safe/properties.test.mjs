/** a1: the name sieve is never narrower than this disk, and sameNameOnDisk says what the disk says. */
const a1 = (L) => property('a1 name sieve vs the disk', (g) => {
  const a = name(g), b = g.chance(0.75) ? variant(g, a) : name(g);
  if (a === b) return null;
  const d = T.fresh('a1');
  try { writeFileSync(join(d, a), 'x'); } catch { return null; }   // a name this disk refuses
  const disk = inode(join(d, b)) === inode(join(d, a));
  const said = L.files.sameNameOnDisk(d, a, b);
  if (said !== disk) return { a, b, disk, sameNameOnDisk: said };
  if (disk && L.files.wideFold(a) !== L.files.wideFold(b)) return { a, b, disk, wideFold: [L.files.wideFold(a), L.files.wideFold(b)] };
  // on Linux a disk keeps every spelling apart: exact only
  if (!MAC && disk) return { a, b, linux: 'two spellings opened as one file' };
  return null;
});

/** a2: a lockfile under any spelling the disk opens as the package manager's name gets that lockfile's verdict; under
 *  one it does not, the manager does not read it, and neither does Wardlatch. */
const a2 = (L) => property('a2 lockfile names', (g) => {
  const shrink = g.chance(0.2), kind = shrink ? 'npm' : g.pick(['npm', 'yarn', 'pnpm']), real = FILE[kind];
  const spelled = variant(g, shrink ? 'npm-shrinkwrap.json' : real);
  const d = T.fresh('a2');
  try { writeFileSync(join(d, spelled), lockText(g, kind)); } catch { return null; }
  const want = [FILE.npm, 'npm-shrinkwrap.json', FILE.yarn, FILE.pnpm].filter((n) => inode(join(d, n)) === inode(join(d, spelled)));
  const got = walkVerdicts(L, [d]).rows;
  // what the manager opens under its own name is this file: Wardlatch reads it and finds the pin
  if (want.length && !(got.length === 1 && got[0].verdict === 'EXPOSED')) return { spelled, opensAs: want, got };
  if (!want.length && got.length) return { spelled, opensAs: 'nothing', got };
  return null;
});

/** a3: a `*` segment matches every spelling the disk opens as a name the pattern matches (on Linux: exactly). */
const a3 = (L) => property('a3 star segments', (g) => {
  const [pattern, make] = g.pick([['Xcode*.app', (s) => `Xcode${s}.app`], ['php@*', (s) => `php@${s}`], ['terraform_*', (s) => `terraform_${s}`], ['ea-php*', (s) => `ea-php${s}`]]);
  const exact = make(g.chance(0.3) ? '' : name(g, 0, 4));
  const spelled = variant(g, exact);
  const d = T.fresh('a3');
  try { writeFileSync(join(d, exact), 'x'); } catch { return null; }
  const same = inode(join(d, spelled)) === inode(join(d, exact));
  if (!same) return null;
  const ok = L.files.segmentTester(pattern)(spelled);
  return ok ? null : { pattern, exact, spelled, disk: 'one file', segmentTester: false };
});

/** a4: a program asked for by name on PATH is found exactly when the disk opens that name in the PATH folder. */
const a4 = (L) => property('a4 PATH by name', (g) => {
  const d = T.fresh('a4'), spelled = variant(g, g.pick(['php', 'php8.3', 'node', 'curl']));
  const wanted = spelled.toLowerCase().normalize('NFC').replace(/[^\x20-\x7e]/g, '') || 'php';
  try { writeFileSync(join(d, spelled), '#!/bin/sh\n', { mode: 0o755 }); } catch { return null; }
  const opens = inode(join(d, wanted)) !== null;
  const r = L.binaries.copiesMatching(`^${wanted.replace(/[.]/g, '\\.')}$`, d, [], [], wanted, []);
  const found = r.run.length + r.notRun.length > 0;
  return found === opens ? null : { spelled, wanted, diskOpens: opens, found };
});


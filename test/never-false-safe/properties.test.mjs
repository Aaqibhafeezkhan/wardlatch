const STATUS_LINE = /^(SAFE|EXPOSED|UNKNOWN|REVIEW) {1,3} /;
/** d: one machine state, run as text and as --json: the summary line, the status lines and the rows agree, and so do
 *  the exit codes. → null or what disagrees. */
function d(m, bin = BIN) {
  const args = ['--no-containers', ...OFFLINE.flatMap((i) => ['--incident', i]), '--paths', m.root];
  const run = (json) => execFileRun(bin, [...args, ...(json ? ['--json'] : [])], m.home, m.root);
  const t = run(false), j = run(true);
  let rows; try { rows = JSON.parse(j.stdout).results; } catch { return `--json is not JSON (exit ${j.status}): ${j.stderr.slice(0, 300)}`; }
  const jc = countOf(rows);
  const sm = /\n(\d+) safe · (\d+) exposed · (\d+) could not be tested(?: · (\d+) to review)?\n/.exec(t.stdout);
  if (!sm) return `no summary line in the text: ${t.stdout.slice(-400)}`;
  const tc = { SAFE: +sm[1], EXPOSED: +sm[2], UNKNOWN: +sm[3], REVIEW: +(sm[4] ?? 0) };
  const lines = { SAFE: 0, EXPOSED: 0, UNKNOWN: 0, REVIEW: 0 };
  for (const l of t.stdout.split('\n')) { const x = STATUS_LINE.exec(l); if (x) lines[x[1]]++; }
  const withdrawn = (t.stdout.match(/^UNKNOWN {2}the SAFE line for .* above is withdrawn$/gm) ?? []).length;
  lines.SAFE -= withdrawn; lines.UNKNOWN -= withdrawn; // a withdrawn SAFE is printed, then its UNKNOWN correction
  const lineCounts = { ...lines, UNKNOWN: lines.UNKNOWN + withdrawn };
  if (JSON.stringify(tc) !== JSON.stringify(jc)) return `text summary ${JSON.stringify(tc)} != --json rows ${JSON.stringify(jc)}`;
  if (JSON.stringify(lineCounts) !== JSON.stringify(jc)) return `text status lines ${JSON.stringify(lineCounts)} != --json rows ${JSON.stringify(jc)}`;
  if (t.status !== j.status) return `exit ${t.status} (text) != ${j.status} (--json)`;
  const again = run(true);
  if (again.stdout !== j.stdout) return 'two --json runs of one machine state differ';
  return null;
}
function execFileRun(bin, args, home, cwd) {
  try { return { stdout: execFileSync(process.execPath, [bin, ...args], { encoding: 'utf8', env: { HOME: home, PATH: '/usr/bin:/bin', LANG: 'C', ...(process.env.NODE_OPTIONS ? { NODE_OPTIONS: process.env.NODE_OPTIONS } : {}) }, cwd, maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] }), stderr: '', status: 0 }; } catch (e) { return { stdout: String(e.stdout ?? ''), stderr: String(e.stderr ?? ''), status: e.status }; }
}
test('d output agreement: text, --json and the summary counts agree for one machine state, and two runs are the same', () => {
  assert.equal(d(machine('d')), null);
});

